       n_strict_0p1=sum(x$concordant_01[ok],na.rm=TRUE),
       n_recovery_reversals=if(all(is.na(vv))) NA_integer_ else sum(vv,na.rm=TRUE),
       n_recovery_evaluable=if(all(is.na(vv))) NA_integer_ else sum(!is.na(vv)))
