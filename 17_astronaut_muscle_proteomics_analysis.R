normalize_times <- function(x) {
 y <- clean(x)
 ifelse(y %in% c("pre","preflight","prelaunch","baseline","before","rminus60","r60pre","1","t0"),"Pre",
 ifelse(y %in% c("r0","rplus0","landing","post","postflight","return","recovery0","2","t1"),"R0",
 ifelse(y %in% c("r14","rplus14","recovery14","day14","14days","t2","3"),"R14",NA_character_)))
}
normalize_astronaut <- function(x) {
 y<-toupper(trimws(as.character(x)))
 y<-sub("^ASTRONAUT[_ -]*","",y)
 y<-sub("^([A-E]).*$","\\1",y)
 ifelse(y %in% LETTERS[1:5],y,NA_character_)
}
# Catch future regressions in case/punctuation handling before loading datasets.
if (!identical(unname(normalize_times(c("Pre", "R0", "R14"))), c("Pre", "R0", "R14"))) {
 stop_now("Internal timepoint normalization test failed; aborting before any analysis.")
}
collapse_gene <- function(d) {
 # One protein group per mapped gene is sometimes violated. Median within
 # astronaut/timepoint across entries; flag duplicates in QC beforehand.
 if(!nrow(d)) return(d)
 aggregate(d$log2_abundance,
       by=list(gene=d$gene,astronaut=d$astronaut,timepoint=d$timepoint),
       FUN=function(z) if(all(!is.finite(z))) NA_real_ else median(z[is.finite(z)])) |>
   setNames(c("gene","astronaut","timepoint","log2_abundance"))
}
validate_long <- function(d,source) {
 must<-c("gene","astronaut","timepoint","log2_abundance")
 if(!all(must %in% names(d))) stop_now("Malformed quantitative input for ",source)
 n_input <- nrow(d)
 valid_gene <- !is.na(extract_symbol(d$gene))
 valid_astronaut <- !is.na(normalize_astronaut(d$astronaut))
 valid_timepoint <- !is.na(normalize_times(d$timepoint))
 valid_abundance <- is.finite(safe_num(d$log2_abundance))
 log_msg(source, " input QC: ", n_input, " technical rows; valid gene=",sum(valid_gene),
   ", astronaut=",sum(valid_astronaut),", timepoint=",sum(valid_timepoint),
   ", abundance=",sum(valid_abundance),".")
 d <- d[valid_gene & valid_astronaut & valid_timepoint & valid_abundance,must,drop=FALSE]
 if(!nrow(d)) stop_now(source, ": all ",n_input," measurements were removed by QC; see validity counts in analysis_log.txt. ",
   "Check sample names, timepoint labels and positive LFQ intensities.")
 d$gene <- extract_symbol(d$gene)
 d$astronaut <- normalize_astronaut(d$astronaut)
 d$timepoint <- normalize_times(d$timepoint)
 d$log2_abundance <- safe_num(d$log2_abundance)
 d$study <- rep(source,nrow(d))
 d
}
make_effects <- function(long,study) {
 if(is.null(long)||!nrow(long)) return(data.frame())
 # Normalize technical replicates WITHIN biopsy using median log2-abundance.
 biop <- collapse_gene(long)
 write_tsv(biop,paste0(study,"_biopsy_level_log2_abundance.tsv"))
 keys<-unique(biop[c("gene","astronaut")]); effects<-keys
 for(tp in c("Pre","R0","R14")) {
  subset <- biop[biop$timepoint==tp,c("gene","astronaut","log2_abundance"),drop=FALSE]
  names(subset)[3]<-tp
  effects<-merge(effects,subset,by=c("gene","astronaut"),all.x=TRUE)
 }
 effects$postflight_log2FC <- effects$R0-effects$Pre
 effects$recovery_log2FC <- effects$R14-effects$R0
 effects$residual_log2FC <- effects$R14-effects$Pre
 effects$study <- study
 effects <- effects[,c("study","gene","astronaut","Pre","R0","R14","postflight_log2FC","recovery_log2FC","residual_log2FC")]
 write_tsv(effects,paste0(study,"_astronaut_protein_changes.tsv"))
 effects
}

# Murgia 2024 Supplementary Tables S1-S10:
# Files MOESM3..MOESM12 correspond to S1..S10. They contain already-log2
# LFQ intensities (ca. 10-25), NOT raw intensities or explicit log2FC columns.
# Different proteins are selected/curated into different tables; the combined
# union is NOT a representative proteome-wide background.
#
# Layout notes validated against the authors' original files:
# S1 (MOESM3) left side A2:X is astronaut A proteins higher postflight.
# S1 RIGHT side Z2:AW is mistakenly labelled astronaut A, but contains B
# intensities and EXACTLY duplicates S2 RIGHT (AA2:AX); NEVER count it.
# S2 (MOESM4) LEFT A2:X has astronaut B proteins higher postflight,
# and RIGHT AA2:AX has astronaut B proteins LOWER postflight.
# Explicit source-layout checks avoid both omission and double-counting.
# S3,S4 (MOESM5,6): 30 intensity columns, 15 per astronaut.
# S5-S8 (MOESM7..10): 15 intensity columns for ONE astronaut each.
# S9 (MOESM11): mitochondria-sum NORMALISED data - excluded from pooled input.
# S10 (MOESM12): curated 109 antioxidant proteins, both astronauts.
#
# Repeated proteins across supplementary tables are NOT independent proteins.
# For each (gene,astronaut) retain ONE entire source table's technical data,
# preferring the general comparisons (S1/S2) over common-protein tables and
# functional subsets. If multiple protein groups map to one gene within the
# same table, prefer the group with the highest unique-peptide count.
# 3/5 valid technical LFQ values required at BOTH Pre and R+0; otherwise the
# entry is not comparable. Day-14 is set missing if fewer than 3/5 values.

murgia_excel_path <- function(n) {
 base<-sprintf("41526_2024_406_MOESM%d_ESM.xlsx",n)
 direct<-file.path(MURGIA_DIR,base)
 if(file.exists(direct)) return(direct)
 paths<-list.files(MURGIA_DIR,pattern=paste0("^",sub("\\.xlsx$","",base),"\\.xlsx$"),
                   recursive=TRUE,full.names=TRUE,ignore.case=TRUE)
 if(length(paths)>1L) stop_now("More than one copy of ",base," in ",MURGIA_DIR)
 if(length(paths)) paths[1] else direct
}
murgia_assay_label <- function(header) {
 h<-tolower(as.character(header))
 if(!grepl("^lfq intensity",h)) return(c(NA_character_,NA_character_))
 a<-if(grepl("astroa|ak_",h)) "A" else
     if(grepl("astrob|02_",h)) "B" else NA_character_
 tp<-if(grepl("rp14",h)) "R14" else
     if(grepl("rp0",h)) "R0" else
     if(grepl("pre|bdc",h)) "Pre" else NA_character_
 c(a,tp)
}
read_murgia_lfq_supplements <- function() {
 include_n <- c(3L,4L,5L,6L,7L,8L,9L,10L,12L)
 info<-list(); audit<-list(); candidates<-list()
 for(n in 3L:12L) {
  f<-murgia_excel_path(n)
  table_name<-paste0("S",n-2L)
  if(n==11L) {
   log_msg("Murgia Table S9 excluded: mitochondria-sum-normalised LFQ values use a different measurement scale.")
   audit[[length(audit)+1L]]<-data.frame(table=table_name,file=basename(f),
      exists=file.exists(f),status="EXCLUDED_SEPARATE_NORMALISATION",rows=NA_integer_,
      n_assay_columns=NA_integer_,n_valid_gene_astronaut_groups=NA_integer_)
   next
  }
  if(!file.exists(f)) {
   log_msg("Murgia ",table_name," missing: ",f)
   audit[[length(audit)+1L]]<-data.frame(table=table_name,file=basename(f),
      exists=FALSE,status="MISSING",rows=NA_integer_,n_assay_columns=NA_integer_,
      n_valid_gene_astronaut_groups=NA_integer_)
   next
  }
  sheets<-readxl::excel_sheets(f)
  valid_for_this_file<-0L
  rows_file<-0L; cols_file<-0L
  for(sheet in sheets) {
   # IMPORTANT SOURCE QC: the 2024 supplementary workbooks put two protein
   # tables side-by-side. S1's apparent right-hand astronaut-A table actually
   # contains astronaut-B samples identical to the S2 right-hand table.
   # Thus analyse S1 LEFT only, S2 LEFT and RIGHT, without duplication.
   blocks<-if(n==3L) "UP_R0" else if(n==4L) c("UP_R0","DOWN_R0") else "ALL"
   if(n==3L) log_msg("Murgia S1: not importing right-hand block: it duplicates S2 B-down intensities (source anomaly).")
   for(block in blocks) {
    d<-tryCatch({
     if(n %in% c(3L,4L)) {
       first_col_idx<-if(block=="DOWN_R0") 27L else 1L
       last_col_idx<-first_col_idx+23L
       as.data.frame(readxl::read_excel(f,sheet=sheet,
         range=readxl::cell_limits(c(2L,first_col_idx),c(NA_integer_,last_col_idx)),
         col_names=TRUE,.name_repair="unique"))
     } else {
       as.data.frame(readxl::read_excel(f,sheet=sheet,skip=1,
         .name_repair="unique"))
     }
    },error=function(e) {
       log_msg("Murgia ",table_name," / ",sheet," / ",block,
         " Excel read ERROR: ",conditionMessage(e))
       NULL
    })
   if(is.null(d)||!nrow(d)) next
   rows_file<-rows_file+nrow(d)
   gn<-first_col(names(d),c("Gene names","Gene name"))
   if(is.na(gn)) {
     log_msg("Murgia ",table_name," / ",sheet,
       " header QC FAILED; columns seen: ",paste(names(d),collapse=" | "))
     next
   }
   j<-grep("^LFQ intensity",names(d),ignore.case=TRUE)
   assays<-lapply(names(d)[j],murgia_assay_label)
   parsed<-data.frame(j=j,astronaut=vapply(assays,`[`,"",1),
                      timepoint=vapply(assays,`[`,"",2),stringsAsFactors=FALSE)
   parsed<-parsed[!is.na(parsed$astronaut)&!is.na(parsed$timepoint),,drop=FALSE]
   cols_file<-max(cols_file,nrow(parsed))
   expect<-if(n %in% c(3L,4L,7L,8L,9L,10L)) 15L else 30L
   if(nrow(parsed)!=expect) {
    log_msg("Murgia ",table_name," / ",sheet,": unexpected LFQ column count ",
            nrow(parsed)," (expected ",expect,"); skipping worksheet.")
    next
   }
   gp<-first_col(names(d),c("Unique peptides","Razor + unique peptides"))
   sym<-extract_symbol(d[[gn]])
   for(ast in unique(parsed$astronaut)) {
    cols_by_time<-lapply(c("Pre","R0","R14"),function(tp) 
       parsed$j[parsed$astronaut==ast & parsed$timepoint==tp])
    names(cols_by_time)<-c("Pre","R0","R14")
    if(any(lengths(cols_by_time)!=5L)) {
     log_msg("Murgia ",table_name," / ",sheet,": expected 5 injections per biopsy for astronaut ",ast,"; skipped.")
     next
    }
    for(i in seq_len(nrow(d))) {
     if(is.na(sym[i])) next
     # The authors' uploaded supplementary LFQ values are ALREADY log2.
     # Do not apply log2() a second time.
     values<-lapply(cols_by_time,function(jj) safe_num(unlist(d[i,jj,drop=FALSE],use.names=FALSE)))
     nv<-vapply(values,function(z) sum(is.finite(z)),integer(1))
     if(nv["Pre"]<3L || nv["R0"]<3L) next
     if(nv["R14"]<3L) values$R14[]<-NA_real_
     pep<-if(!is.na(gp)) safe_num(d[[gp]][i]) else NA_real_
     if(!is.finite(pep)) pep <- -1
     key<-length(candidates)+1L
     candidates[[key]]<-list(gene=sym[i],astronaut=ast,table=table_name,
          file=basename(f),sheet=paste0(sheet,"::",block),source_row=i+2L,
          source_priority=n,unique_peptides=pep,log2_values=values,
          n_pre=nv["Pre"],n_r0=nv["R0"],n_r14=nv["R14"])
     valid_for_this_file<-valid_for_this_file+1L
    }
   }
   } # end left/right block loop
  } # end worksheet loop
  # S1 and S2 are known to contain valid LFQ measurements. Never quietly
  # produce a scientifically incomplete module if these mandatory inputs fail.
  if(n %in% c(3L,4L) && valid_for_this_file==0L)
   stop_now("Murgia ",table_name," has zero usable proteins despite an existing input file. ",
     "See the logged column names/header error before interpreting the results.")
  audit[[length(audit)+1L]]<-data.frame(table=table_name,file=basename(f),
    exists=TRUE,status="SELECTED_OR_CURATED_LOG2_LFQ",rows=rows_file,
    n_assay_columns=cols_file,n_valid_gene_astronaut_groups=valid_for_this_file)
  log_msg("Murgia ",table_name,": ",valid_for_this_file,
          " candidate gene-astronaut entries with >=3 valid Pre and R0 injections.")
 }
 if(length(audit)) write_tsv(do.call(rbind,audit),"Murgia_supplement_file_QC.tsv")
 if(!length(candidates)) return(data.frame())
 metadata<-do.call(rbind,lapply(candidates,function(z)
    data.frame(gene=z$gene,astronaut=z$astronaut,table=z$table,
     source_file=z$file,source_sheet=z$sheet,source_excel_row=z$source_row,
     source_priority=z$source_priority,unique_peptides=z$unique_peptides,
     valid_pre=z$n_pre,valid_r0=z$n_r0,valid_r14=z$n_r14)))
 # Resolve repeated gene-astronaut across selected/curated tables deterministically:
 # general first; highest peptide support within same table; then source row.
 ordering<-order(metadata$source_priority,-metadata$unique_peptides,metadata$source_excel_row)
 metadata<-metadata[ordering,,drop=FALSE]
 candidates<-candidates[ordering]
 k<-paste(metadata$gene,metadata$astronaut,sep="::")
 kept<-!duplicated(k)
 write_tsv(metadata,"Murgia_all_candidate_protein_groups_and_sources.tsv")
 if(any(!kept)) write_tsv(metadata[!kept,,drop=FALSE],
    "Murgia_overlapping_or_duplicate_protein_groups_NOT_DOUBLE_COUNTED.tsv")
 metadata$chosen<-kept
 write_tsv(metadata[kept,,drop=FALSE],"Murgia_selected_protein_gene_and_source_QC.tsv")
 chosen<-candidates[kept]
 technical<-list()
 for(z in chosen) {
  for(tp in c("Pre","R0","R14")) {
   v<-z$log2_values[[tp]]
   technical[[length(technical)+1L]]<-data.frame(gene=z$gene,
     astronaut=z$astronaut,timepoint=tp,technical_injection=seq_along(v),
     log2_abundance=v,source_table=z$table,source_file=z$file)
