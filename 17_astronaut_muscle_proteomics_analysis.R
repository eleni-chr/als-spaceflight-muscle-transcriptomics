# Choose an exact expected file if present, otherwise an unambiguous match
# inside the correct study folder (including nested subfolders).
find_unique_input <- function(folder, expected, pattern, label) {
  if (file.exists(expected)) return(expected)
  candidates <- list.files(folder, pattern=pattern, recursive=TRUE,
                           full.names=TRUE, ignore.case=TRUE)
  candidates <- candidates[!dir.exists(candidates)]
  if (length(candidates) == 1L) return(candidates)
  if (length(candidates) > 1L) {
    stop(paste0("Multiple possible ", label, " files in ", folder,
      ":\n", paste(basename(candidates), collapse="\n"),
      "\nPlease set the corresponding file variable explicitly."),call.=FALSE)
  }
  expected   # Missing files are handled explicitly by each analysis branch.
}
