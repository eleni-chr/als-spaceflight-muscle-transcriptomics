# Lowercase FIRST, then strip punctuation. Otherwise uppercase timepoints
# (Pre, R0, R14) are mistakenly turned into (re, 0, 14) and all rows fail QC.
clean <- function(x) gsub("[^a-z0-9]+", "", tolower(trimws(as.character(x))))
first_col <- function(nms, options) {
 i <- which(clean(nms) %in% clean(options))
 if(length(i)) nms[i[1]] else NA_character_
}
extract_symbol <- function(x) {
 x <- trimws(as.character(x))
 x[x %in% c("", "NA", "null", "NULL")] <- NA_character_
 # Protein groups with multiple gene symbols are ambiguous: DO NOT pick first.
 x[grepl("[;,|]",x)] <- NA_character_
 toupper(x)
}
safe_num <- function(x) suppressWarnings(as.numeric(gsub(",","",as.character(x))))
read_data <- function(f, sheet=1, skip=0) {
 ext <- tolower(tools::file_ext(f))
 if(ext %in% c("xlsx","xls")) return(as.data.frame(readxl::read_excel(f,sheet=sheet,skip=skip,.name_repair="unique")))
 if(ext=="tsv" || ext=="txt") return(read.delim(f,check.names=FALSE,quote="",comment.char=""))
 if(ext=="csv") return(read.csv(f,check.names=FALSE))
 stop_now("Unsupported file format: ",f)
}
