annotate_effects <- function(d, study_label) {
 if(!nrow(d)) return(data.frame())
 if(!"postflight_log2FC" %in% names(d)) stop_now("Internal effect column missing")
 d$gene<-extract_symbol(d$gene)
 # Avoid falsely counting gene twice per astronaut.
 d<-d[!duplicated(d[c("gene","astronaut")]),,drop=FALSE]
 d<-merge(d,module,by="gene")
 if(!nrow(d)) {
   log_msg(study_label, ": no proteins overlap the frozen module; skipping module-specific outputs.")
   return(data.frame())
 }
 d$aligned_postflight <- d$postflight_log2FC*d$expected
 d$concordant_any <- is.finite(d$aligned_postflight)&d$aligned_postflight>DIR_THRESHOLD
 d$concordant_01 <- is.finite(d$aligned_postflight)&d$aligned_postflight>=0.1
 d$opposite_any <- is.finite(d$aligned_postflight)&d$aligned_postflight< -DIR_THRESHOLD
 if("recovery_log2FC" %in% names(d)) {
  d$aligned_recovery <- d$recovery_log2FC*d$expected
  # An unavailable day-14 measurement is missing data, not a failed reversal.
  complete_recovery <- is.finite(d$aligned_postflight) & is.finite(d$aligned_recovery)
  d$reversal_after_landing <- ifelse(complete_recovery,
     (d$aligned_postflight>0) & (d$aligned_recovery<0), NA)
  complete_day14 <- is.finite(d$postflight_log2FC) & is.finite(d$residual_log2FC)
  d$closer_to_pre_by_day14 <- ifelse(complete_day14,
     abs(d$residual_log2FC)<abs(d$postflight_log2FC), NA)
 } else {
  d$aligned_recovery<-NA_real_
  d$reversal_after_landing<-NA
  d$closer_to_pre_by_day14<-NA
 }
 d$study<-study_label
 d
}
