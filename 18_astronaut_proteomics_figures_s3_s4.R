# PANEL C — MURGIA RECOVERY, GENE BY GENE =====================================
# For each gene and astronaut compare the ABSOLUTE log2 difference from their
# own preflight biopsy at landing (R0) and day 14 (R14).
# delta < 0 means the protein's abundance moves CLOSER to its preflight value.
# This does NOT necessarily imply a reversal of the ALS-defined direction.
recover <- recover[is.finite(recover$postflight_log2FC) &
                   is.finite(recover$residual_log2FC), ]
recover$delta_distance <- abs(recover$residual_log2FC) - abs(recover$postflight_log2FC)
recover$status <- ifelse(recover$delta_distance < 0,
                         "Closer to preflight", "Further from preflight")
recover$astronaut <- factor(recover$astronaut, levels = c("A", "B"))
if (nrow(recover) == 0) stop("Murgia recovery file contains no paired R0 and R14 results")

# Genes are positioned identically in both astronauts; a missing point means that
# the protein was not represented for that astronaut in the selected tables.
gene_order <- names(sort(tapply(recover$delta_distance, recover$gene,
                               function(x) median(x, na.rm = TRUE))))
recover$gene <- factor(recover$gene, levels = gene_order)
if (anyDuplicated(recover[c("gene", "astronaut")])) {
