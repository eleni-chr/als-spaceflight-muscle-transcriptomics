# No study pooling: profile identities remain study-specific (participant overlap
# between the original publications has not been established).
study_name <- function(x) {
  ifelse(grepl("Murgia|PXD028435", x, ignore.case = TRUE), "PXD028435", "PXD081616")
}
profile_order <- c("PXD028435 A", "PXD028435 B", paste("PXD081616", LETTERS[1:5]))
profile_label <- c("PXD028435 A", "PXD028435 B", "PXD081616 A", "PXD081616 B",
                   "PXD081616 C", "PXD081616 D", "PXD081616 E*")

