# Export helper: outputs PNG and vector SVG without changing any data.
save_both <- function(plot, prefix, width, height) {
  png_file <- file.path(OUT, paste0(prefix, ".png"))
  svg_file <- file.path(OUT, paste0(prefix, ".svg"))
  ggplot2::ggsave(filename = png_file, plot = plot, width = width, height = height,
                  units = "in", dpi = DPI, bg = "white", limitsize = FALSE)
  # grDevices::svg is part of base R and does not require svglite.
  grDevices::svg(filename = svg_file, width = width, height = height,
                 onefile = FALSE, bg = "white")
  tryCatch(print(plot), finally = grDevices::dev.off())
  message("Saved:\n  ", png_file, "\n  ", svg_file)
}

