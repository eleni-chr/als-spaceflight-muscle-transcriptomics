concord <- concord[order(concord$profile), ]
if (anyNA(concord$profile) || !identical(as.character(concord$profile), profile_order)) {
  stop("Unexpected astronaut profiles in the concordance table. Inspect this TSV.")
}
if (any(concord$n_concordant > concord$n_evaluable_module_genes)) {
  stop("Invalid directional counts: concordant genes exceed evaluable genes")
}
concord$percentage <- 100 * concord$n_concordant / concord$n_evaluable_module_genes
concord$count_label <- paste0(concord$n_concordant, "/", concord$n_evaluable_module_genes)
concord$study_label <- factor(concord$study_label, c("PXD028435", "PXD081616"))

# Consistent journal-style typography, no unnecessary grids or background fills.
base_theme <- function(base_size = 12) {
  ggplot2::theme_classic(base_size = base_size, base_family = "sans") +
    ggplot2::theme(
      plot.title = ggplot2::element_text(size = base_size + 2,
                                       face = "bold", margin = ggplot2::margin(b = 5)),
      plot.subtitle = ggplot2::element_text(size = base_size - 1,
                                          colour = "#555555", margin = ggplot2::margin(b = 7)),
      axis.title = ggplot2::element_text(size = base_size),
      axis.text = ggplot2::element_text(size = base_size - 1, colour = "#222222"),
      plot.margin = ggplot2::margin(t = 9, r = 16, b = 9, l = 10)
    )
}
