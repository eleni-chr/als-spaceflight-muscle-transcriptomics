# OPTIONAL SECOND FIGURE — MEASURED MODULE PROTEINS (DETAIL) ====================
# Two separate heatmaps prevent all the empty cross-study cells in the original
# combined heatmap. Colour always describes actual protein change (R0 vs Pre),
# NOT agreement with ALS; ALS up/down labels are shown next to gene names.
heatmap_study <- function(data, astronauts, title) {
  stopifnot(all(c("gene", "ALS_direction", "astronaut", "postflight_log2FC") %in% names(data)))
  data$gene <- as.character(data$gene)
  direction <- unique(data[c("gene", "ALS_direction")])
  if (anyDuplicated(direction$gene)) stop("Gene has conflicting ALS directions")
  # ALS-up genes first, followed by ALS-down genes; order alphabetically within.
  direction <- direction[order(direction$ALS_direction != "up", direction$gene), ]
  direction$gene_label <- paste0(direction$gene, ifelse(direction$ALS_direction == "up",
                                                      " (ALS up)", " (ALS down)"))
  order_genes <- rev(direction$gene_label)

  # Complete only within the study; BLACK tiles indicate unavailable study-profile
  # values in the published SUBSET, not absence of the protein from the biopsies.
  expanded <- expand.grid(gene = direction$gene, astronaut = astronauts,
                          KEEP.OUT.ATTRS = FALSE, stringsAsFactors = FALSE)
  expanded <- merge(expanded, data[c("gene", "astronaut", "postflight_log2FC")],
                    by = c("gene", "astronaut"), all.x = TRUE, sort = FALSE)
  expanded <- merge(expanded, direction[c("gene", "gene_label")],
                    by = "gene", all.x = TRUE, sort = FALSE)
  expanded$gene_label <- factor(expanded$gene_label, levels = order_genes)
  expanded$astronaut <- factor(expanded$astronaut, levels = astronauts)

  ggplot2::ggplot(expanded,
                  ggplot2::aes(x = astronaut, y = gene_label, fill = postflight_log2FC)) +
    ggplot2::geom_tile(width = .94, height = .94, colour = "white", linewidth = .6) +
    ggplot2::scale_fill_gradient2(
      low = "#3E70A0", mid = "#FFFFFF", high = "#BD514A",
      midpoint = 0, limits = c(-3, 3), oob = scales::squish,
      na.value = "#000000", name = "R0 vs Pre\nprotein log2FC",
      breaks = c(-3, -1.5, 0, 1.5, 3), labels = c("≤-3", "-1.5", "0", "1.5", "≥3")
    ) +
    ggplot2::guides(fill = ggplot2::guide_colourbar(
      direction = "vertical", title.position = "top",
      barheight = grid::unit(53, "mm"), barwidth = grid::unit(5.5, "mm")
    )) +
    ggplot2::labs(title = title,
      subtitle = paste(length(unique(direction$gene)), "module-associated proteins in published subset"),
      x = "Astronaut", y = NULL) +
    base_theme(11) +
    ggplot2::theme(
      axis.text.y = ggplot2::element_text(size = 10),
      axis.text.x = ggplot2::element_text(size = 11),
      axis.ticks = ggplot2::element_blank(),
      legend.position = "right",
      legend.direction = "vertical",
      legend.title = ggplot2::element_text(size = 10),
      legend.text = ggplot2::element_text(size = 9)
    )
}

